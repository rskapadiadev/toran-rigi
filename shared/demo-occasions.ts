import { type CultureId, cultures } from './cultures';
import { type DemoInvitation, maps, t } from './demo-kit';
import { defaultSectionsFor, type OccasionId, occasions } from './occasions';
import type { SectionConfig, SectionType } from './types';

function sections(
    occasion: OccasionId,
    culture: CultureId,
    extra: SectionType[] = [],
): SectionConfig[] {
    const base = defaultSectionsFor(occasions[occasion], cultures[culture]);
    return [...base, ...extra.filter((s) => !base.includes(s))].map((type) => ({
        type,
        enabled: true,
    }));
}

