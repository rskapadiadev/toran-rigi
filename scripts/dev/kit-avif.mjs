// AVIF copies of a kit's artwork, about half the bytes of the WebP at the same sharpness.
// Writes public/kits/<kit>/<name>.avif next to each WebP and lists them in shared/kit-avif.ts,
// which photoUrl() reads. The WebP stays: browsers without AVIF fall back to it (src/routes/__root.tsx).
//
//   node scripts/dev/kit-avif.mjs            (re-encodes only what changed)
//   node scripts/dev/kit-avif.mjs --force
import fs from 'node:fs';
import path from 'node:path';

import sharp from 'sharp';

const KITS = ['phoolwari'];
// Drawn as a CSS background, where a failed AVIF can't fall back: keep these WebP only.
const SKIP = new Set(['/kits/phoolwari/meadow.webp']);
// q60 matches the WebP side by side at 2× zoom; q50 softens fine texture.
const QUALITY = 60;
// Not worth a second file unless it saves at least this much.
const MIN_SAVING = 0.15;

const force = process.argv.includes('--force');
const listed = [];
let before = 0;
let after = 0;

for (const kit of KITS) {
    const dir = path.join('public/kits', kit);
    for (const file of fs
        .readdirSync(dir)
        .filter((f) => f.endsWith('.webp'))
        .sort()) {
        const key = `/kits/${kit}/${file}`;
        if (SKIP.has(key)) continue;
        const src = path.join(dir, file);
        const out = src.replace(/\.webp$/, '.avif');
        const fresh = fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(src).mtimeMs;
        if (force || !fresh)
            await sharp(src)
                .avif({
                    quality: QUALITY,
                    effort: 6,
                })
                .toFile(out);
        const a = fs.statSync(src).size;
        const b = fs.statSync(out).size;
        if (b > a * (1 - MIN_SAVING)) {
            fs.rmSync(out);
            console.log(`skip  ${key} (AVIF saves too little)`);
            continue;
        }
        before += a;
        after += b;
        listed.push(key);
        console.log(
            `${String(Math.round(a / 1024)).padStart(4)} → ${String(Math.round(b / 1024)).padStart(4)} KB  ${key}`,
        );
    }
}

const body = listed.map((k) => `    '${k}',`).join('\n');
fs.writeFileSync(
    'shared/kit-avif.ts',
    `// Generated by scripts/dev/kit-avif.mjs: kit artwork that also ships as AVIF (same name, .avif).\nexport const kitAvif: ReadonlySet<string> = new Set([\n${body}\n]);\n`,
);
console.log(
    `\n${String(listed.length)} images: ${String(Math.round(before / 1024))} KB → ${String(Math.round(after / 1024))} KB`,
);
